module main

import math

type IhUnary = fn (f64) f64

struct IhVector {
	kind      int
	input     u64
	native    u64
	flags     int
	reference u64
	rounding  int
}

fn ih_api(kind int) IhUnary {
	name := ['_acosh', '_asinh', '_atanh']![kind]
	return unsafe { IhUnary(voidptr(runtime_symbol('/usr/lib/libSystem.B.dylib', name) or { panic(err) })) }
}

fn ih_flags() int {
	native := C.fetestexcept(int(C.FE_ALL_EXCEPT))
	mut result := 0
	for i, flag in [int(C.FE_INVALID), int(C.FE_DIVBYZERO), int(C.FE_OVERFLOW), int(C.FE_UNDERFLOW),
		int(C.FE_INEXACT)]! {
		if native & flag != 0 { result |= 1 << i }
	}
	return result
}

fn ih_check(row IhVector, preset int, sentinel int) {
	call := ih_api(row.kind)
	rounding := [i32(C.FE_TONEAREST), i32(C.FE_TOWARDZERO), i32(C.FE_UPWARD), i32(C.FE_DOWNWARD)]![row.rounding]
	assert C.fesetround(rounding) == 0
	assert C.feclearexcept(int(C.FE_ALL_EXCEPT)) == 0
	assert C.feraiseexcept(preset) == 0
	previous := ih_flags()
	darwin_set_errno(sentinel)
	result := call(math.f64_from_bits(row.input))
	bits := math.f64_bits(result)
	errno := unsafe { *C.ios_errno_address() }
	flags := ih_flags()
	assert errno == sentinel
	assert C.fegetround() == rounding
	assert flags == (previous | row.flags), 'kind=${row.kind} input=${row.input.hex()} mode=${row.rounding} flags=${flags} expected=${previous | row.flags}'
	if row.native & 0x7ff0000000000000 == 0x7ff0000000000000 || row.native & 0x7fffffffffffffff == 0 {
		assert bits == row.native, 'kind=${row.kind} input=${row.input.hex()} mode=${row.rounding} result=${bits.hex()} native=${row.native.hex()}'
	} else {
		assert bits >> 63 == row.reference >> 63
		distance := if bits > row.reference { bits - row.reference } else { row.reference - bits }
		assert distance <= if row.rounding == 0 { u64(2) } else { u64(3) }, 'kind=${row.kind} input=${row.input.hex()} mode=${row.rounding} result=${bits.hex()} MPFR=${row.reference.hex()} ULP=${distance}'
	}
}

fn ih_worker(id int) {
	mut environment := [32]u64{}
	assert C.fegetenv(unsafe { voidptr(&environment[0]) }) == 0
	defer { C.fesetenv(unsafe { voidptr(&environment[0]) }) }
	for row in ih_vectors {
		ih_check(row, if id % 2 == 0 { int(C.FE_INVALID) } else { int(C.FE_DIVBYZERO) }, 70 + id)
	}
}

fn test_inverse_hyperbolic() {
	mut environment := [32]u64{}
	assert C.fegetenv(unsafe { voidptr(&environment[0]) }) == 0
	previous := unsafe { *C.ios_errno_address() }
	defer {
		C.fesetenv(unsafe { voidptr(&environment[0]) })
		darwin_set_errno(previous)
	}
	for name in ['_acosh', '_asinh', '_atanh']! {
		assert runtime_symbol('/usr/lib/libSystem.B.dylib', name) or { panic(err) } != 0
		for library in ['/usr/lib/libobjc.A.dylib', '/usr/lib/libz.1.dylib',
			'/System/Library/Frameworks/Foundation.framework/Foundation']! {
			if _ := runtime_symbol(library, name) {
				assert false
			}
		}
	}
	for name in ['_acoshf', '_asinhf', '_atanhf', '_not_inverse_hyperbolic']! {
		if _ := inverse_hyperbolic_symbol(name) {
			assert false
		}
	}
	assert ih_vectors.len > 1600
	for preset in [0, int(C.FE_DIVBYZERO), int(C.FE_INVALID) | int(C.FE_OVERFLOW)]! {
		for row in ih_vectors { ih_check(row, preset, 42) }
	}
	assert C.fesetround(i32(C.FE_DOWNWARD)) == 0
	assert C.feclearexcept(int(C.FE_ALL_EXCEPT)) == 0
	assert C.feraiseexcept(int(C.FE_DIVBYZERO)) == 0
	main_flags := ih_flags()
	darwin_set_errno(29)
	mut workers := []thread{}
	for id in 0 .. 8 { workers << spawn ih_worker(id) }
	workers.wait()
	assert unsafe { *C.ios_errno_address() } == 29
	assert C.fegetround() == C.FE_DOWNWARD && ih_flags() == main_flags
	println('IOS-INVERSE-HYPERBOLIC: three scoped double ABI imports, native NaN payloads and signs, poles and domain errors, signed zeros and subnormals, tiny underflow boundaries in four rounding modes, preserved errno and sticky flags, MPFR accuracy vectors and eight concurrent callers')
}

