module main

import crypto.sha256
import os
import strconv

fn generate(source string, destination string) ! {
	data := os.read_file(source)!
	if !data.starts_with('# DerivedNumericType-13.0.0.txt') {
		return error('expected Unicode 13 numeric type data')
	}
	mut ranges := []string{}
	for line in data.split_into_lines() {
		parts := line.all_before('#').split(';').map(it.trim_space())
		if parts.len != 2 || parts[1] !in ['Decimal', 'Digit'] { continue }
		bounds := parts[0].split('..')
		first := strconv.parse_uint(bounds[0], 16, 32)!
		last := if bounds.len == 2 { strconv.parse_uint(bounds[1], 16, 32)! } else { first }
		ranges << '\t[ u32(0x' + first.hex() + '), 0x' + last.hex() + ' ]!,'
	}
	if ranges.len == 0 { return error('missing numeric type ranges') }
	output := '// SPDX-License-Identifier: GPL-2.0-or-later\n// Generated by generate-key-digits.v from Unicode 13.0 Numeric_Type Decimal/Digit.\n// https://www.unicode.org/Public/13.0.0/ucd/extracted/DerivedNumericType.txt\n// Source SHA-256: ' + sha256.sum(data.bytes()).hex() + '\nmodule androidrun\n\nconst digit_ranges = [\n' + ranges.join('\n') + '\n]\n\nfn character_digit(character string) bool {\n\tpoints := character.runes()\n\tif points.len == 0 { return false }\n\tfor point in points {\n\t\tmut found := false\n\t\tfor bounds in digit_ranges { if u32(point) >= bounds[0] && u32(point) <= bounds[1] { found = true; break } }\n\t\tif !found { return false }\n\t}\n\treturn true\n}\n'
	os.write_file(destination, output)!
}

fn main() {
	if os.args.len != 3 {
		eprintln('usage: generate-key-digits DerivedNumericType-13.txt OUTPUT.v')
		exit(2)
	}
	generate(os.args[1], os.args[2]) or {
		eprintln(err)
		exit(1)
	}
}
