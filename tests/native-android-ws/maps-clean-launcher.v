fn hash(path string) !string {
	mut file := os.open(path)!
	defer { file.close() }
	mut sum := sha256.new()
	mut buffer := []u8{len: 1024 * 1024}
	for {
		n := file.read(mut buffer) or { if err is os.Eof { break }; return err }
		if n == 0 { break }
		sum.write(buffer[..n])!
	}
	return sum.sum([]u8{}).hex()
}
fn write_json[T](path string, value T) ! { os.write_file(path, json2.encode(value, prettify: true) + '\n')! }
fn object(path string) !map[string]json2.Any { return json2.decode[map[string]json2.Any](os.read_file(path)!)! }
fn map_file(path string) !map[string]string { return json2.decode[map[string]string](os.read_file(path)!)! }
fn checked(argv []string) !string {
	r := os.exec(argv)
	if r.exit_code != 0 { return error(argv.str() + ': ' + r.output) }
	return r.output
}
fn trace_delta(old string, clean string) ! {
	mut lines := []string{}
	mut removed := []string{}
	for line in old.split_into_lines() {
		if line.trim_space().starts_with("os.setenv('VINIX_ANDROID_TRACE_") { removed << line.trim_space(); continue }
		lines << line
	}
	if removed.len != 10 || lines.join('\n') + '\n' != clean || clean.contains('VINIX_ANDROID_TRACE_') {
		return error('clean launcher must differ only by ten historical trace setters')
	}
}
fn same(pins map[string]string) ! {
	for path, pin in pins { if hash(path)! != pin { return error('build input changed: ' + path) } }
}
fn equal_maps(actual map[string]string, expected map[string]string) ! {
	if actual.len != expected.len { return error('build closure length differs') }
	for path, pin in expected { if actual[path] or { '' } != pin { return error('build closure differs: ' + path) } }
}
fn inventory(root string, relative string, mut entries map[string]string) ! {
	for name in os.ls(root + '/' + relative)! {
		key := if relative == '' { name } else { relative + '/' + name }
		if key == 'sha256.json' { continue }
		path := root + '/' + key
		match os.lstat(path)!.get_filetype() {
			.regular { entries[key] = hash(path)! }
			.directory { entries[key] = 'directory'; inventory(root, key, mut entries)! }
			else { return error('unexpected build evidence entry: ' + path) }
		}
	}
}
fn copy_input(root string, path string, mut pins map[string]string) ! {
	resolved := os.real_path(path)
	if resolved in pins { return }
	if os.lstat(resolved)!.get_filetype() != .regular { return error('regular build input required: ' + path) }
	pins[resolved] = hash(resolved)!
	to := root + '/inputs/' + resolved.trim_left('/')
	os.mkdir_all(os.dir(to))!
	checked(['cp', '-c', resolved, to])!
	if hash(to)! != pins[resolved]! { return error('retained build input differs: ' + path) }
}
fn cc_paths(deps string, output string, cwd string, build_root string, argv []string) []string {
	mut candidates := deps.replace('\\\n', ' ').all_after(':').fields()
	for line in output.split_into_lines() {
		path := line.trim_space()
		if path.starts_with('/') && (path.ends_with('.a') || path.ends_with('.o')) { candidates << path }
	}
	for arg in argv { if !arg.starts_with('-') && (arg.ends_with('.c') || arg.ends_with('.o')) { candidates << arg } }
	mut paths := []string{}
	for candidate in candidates {
		path := if os.is_abs_path(candidate) { candidate } else { cwd + '/' + candidate }
		// These C and object files are generated by this recorded V invocation.
		if path.starts_with(build_root + '/') && path.contains('.v3cc.') { continue }
		if path !in paths { paths << path }
	}
	return paths
}
fn cc_argv(cc string, original []string, stem string, cwd string, root string) []string {
	mut argv := [cc]
	argv << original
	is_source := original.any(it.ends_with('.c'))
	is_probe := original.any(it in ['-M', '-MM', '-E', '-S', '-fsyntax-only'])
	if is_source && !is_probe { argv << ['-MD', '-MF', stem + '.d'] }
	if is_source && !is_probe && '-c' !in original {
		argv << '-Wl,-t'
		// Keep GCC's generated object beside the generated C until V removes its
		// private build directory; do not mistake a deleted GCC temp for an input.
		if cwd.starts_with(root + '/') && cwd.contains('.v3cc.') { argv << '-save-temps=obj' }
	}
	return argv
}
fn record_cc() ! {
	root := os.dir(os.executable())
	cc := os.read_file(root + '/real-gcc.txt')!.trim_space()
	phase := os.getenv('VINIX_LAUNCHER_BUILD_PHASE')
	if phase !in ['discovery', 'run-android-calculator'] { return error('compiler recorder phase missing') }
	stem := root + '/cc-records/' + phase + '-' + os.getpid().str()
	original := os.args[1..].clone()
	cwd := os.getwd()
	argv := cc_argv(cc, original, stem, cwd, root)
	mut generated := map[string]string{}
	for arg in original {
		if !arg.ends_with('.c') { continue }
		path := if os.is_abs_path(arg) { arg } else { cwd + '/' + arg }
		if path.starts_with(root + '/') && path.contains('.v3cc.') && os.is_file(path) {
			generated[path] = hash(path)!
			os.cp(path, stem + '.c')!
		}
	}
	r := os.exec(argv)
	os.write_file(stem + '.log', r.output)!
	deps := if os.is_file(stem + '.d') { os.read_file(stem + '.d')! } else { '' }
	inputs := cc_paths(deps, r.output, cwd, root, original)
	write_json(stem + '.json', {'argv': json2.Any(argv), 'original_argv': json2.Any(original),
		'cwd': json2.Any(cwd), 'build_root': json2.Any(root), 'exit_code': json2.Any(r.exit_code),
		'inputs': json2.Any(inputs), 'generated_c': json2.decode[json2.Any](json2.encode(generated))!})!
	print(r.output)
	exit(r.exit_code)
}
fn consumed_paths(root string, stem string) ![]string {
	mut paths := os.read_lines(root + '/' + stem + '-v-files.txt')!
	for name in os.ls(root + '/cc-records')! {
		if !name.starts_with(stem + '-') || !name.ends_with('.json') { continue }
		record := object(root + '/cc-records/' + name)!
		path := root + '/cc-records/' + name.all_before_last('.json')
		original := record['original_argv']!.as_array().map(it.str())
		recorded_stem := record['build_root']!.str() + '/cc-records/' + name.all_before_last('.json')
		expected_argv := cc_argv(os.read_file(root + '/real-gcc.txt')!.trim_space(), original, recorded_stem, record['cwd']!.str(), record['build_root']!.str())
		if record['argv']!.as_array().map(it.str()) != expected_argv { return error('compiler argv record differs: ' + name) }
		if record['exit_code']!.int() != 0 && original.any(it.ends_with('.c')) {
			return error('source compilation failed: ' + name)
		}
		deps := if os.is_file(path + '.d') { os.read_file(path + '.d')! } else { '' }
		inputs := cc_paths(deps, os.read_file(path + '.log')!, record['cwd']!.str(), record['build_root']!.str(), record['original_argv']!.as_array().map(it.str()))
		if inputs != record['inputs']!.as_array().map(it.str()) { return error('compiler dependency record differs: ' + name) }
		for _, pin in record['generated_c']!.as_map() { if hash(path + '.c')! != pin.str() { return error('generated C snapshot differs') } }
		paths << inputs
	}
	paths << '/Users/alex/code/v/v_old'
	paths << os.read_file(root + '/build-root.txt')!.trim_space() + '/aarch64-linux-musl-gcc'
	tools := map_file(root + '/compile-tools.json')!
	if tools.len != 5 { return error('exact crosscompiler program closure required') }
	for name in ['gcc', 'cc1', 'as', 'ld', 'collect2'] { paths << tools[name]! }
	mut result := []string{}
	for path in paths {
		if path !in result { result << path }
	}
	return result
}
fn closure(root string, stem string) !map[string]string {
	mut pins := map[string]string{}
	mut resolved_paths := map[string]string{}
	for path in consumed_paths(root, stem)! {
		resolved := os.real_path(path)
		if !os.is_file(resolved) { return error('missing consumed build input: ' + path) }
		resolved_paths[path] = resolved
		pins[resolved] = hash(resolved)!
	}
	if pins.len < 20 || !pins.keys().any(it.ends_with('/libc.a')) || !pins.keys().any(it.ends_with('/libgcc.a')) {
		return error('incomplete V/header/static-library/tool closure')
	}
	write_json(root + '/' + stem + '-resolved-inputs.json', resolved_paths)!
	return pins
}
fn compile_argv(root string, stem string, cc string) []string {
	return ['/Users/alex/code/v/v_old', '-nocache', '-os', 'linux', '-arch', 'arm64', '-cc', cc,
		'-gc', 'none', '-showcc', '-dump-files', root + '/' + stem + '-v-files.txt',
		'-cflags', '-O2 -D_GNU_SOURCE -static',
		'-ldflags', '-static', '-o', root + '/' + stem, root + '/source/launcher.v']
}
fn compile(root string, stem string, cc string, before map[string]string) ! {
	argv := compile_argv(root, stem, cc)
	same(before)!
	mut receipt := {'argv': json2.Any(argv), 'started_utc': json2.Any(time.utc().str()),
		'input_sha256': json2.decode[json2.Any](json2.encode(before))!}
	write_json(root + '/' + stem + '-before.json', receipt)!
	os.setenv('VINIX_LAUNCHER_BUILD_PHASE', stem, true)
	r := os.exec(argv)
	os.write_file(root + '/' + stem + '.log', r.output)!
	receipt['completed_utc'] = time.utc().str()
	receipt['exit_code'] = json2.Any(r.exit_code)
	receipt['log_sha256'] = hash(root + '/' + stem + '.log')!
	if r.exit_code == 0 { receipt['output_sha256'] = hash(root + '/' + stem)! }
	same(before)!
	write_json(root + '/' + stem + '-receipt.json', receipt)!
	if r.exit_code != 0 { return error('launcher ' + stem + ' failed: ' + r.output) }
}
fn build(root string) ! {
	if os.exists(root) || os.is_link(root) { return error('fresh build destination required') }
	os.mkdir_all(root + '/source')!
	os.cp(launcher_source, root + '/source/launcher.v')!
	os.cp(historical_source, root + '/source/trace200-launcher.v')!
	os.cp(@FILE, root + '/source/maps-clean-launcher.v')!
	os.cp(os.executable(), root + '/builder')!
	os.cp(os.executable(), root + '/aarch64-linux-musl-gcc')!
	os.mkdir_all(root + '/cc-records')!
	os.write_file(root + '/build-root.txt', os.abs_path(root) + '\n')!
	if hash(historical_source)! != historical_source_pin { return error('wrong historical source reference') }
	trace_delta(os.read_file(historical_source)!, os.read_file(launcher_source)!)!
	cc := os.real_path(os.find_abs_path_of_executable('aarch64-linux-musl-gcc')!)
	mut tools := {'gcc': cc}
	for name in ['cc1', 'as', 'ld', 'collect2'] { tools[name] = checked([cc, '-print-prog-name=' + name])!.trim_space() }
	write_json(root + '/compile-tools.json', tools)!
	os.write_file(root + '/real-gcc.txt', cc + '\n')!
	wrapper := os.abs_path(root + '/aarch64-linux-musl-gcc')
	mut initial := map[string]string{}
	for path in ['/Users/alex/code/v/v_old', cc, root + '/source/launcher.v'] { initial[os.real_path(path)] = hash(path)! }
	compile(root, 'discovery', wrapper, initial)!
	discovered := closure(root, 'discovery')!
	mut frozen := map[string]string{}
	for path, _ in discovered { copy_input(root, path, mut frozen)! }
	write_json(root + '/input-sha256.json', frozen)!
	compile(root, 'run-android-calculator', wrapper, frozen)!
	actual := closure(root, 'run-android-calculator')!
	for path, pin in actual { if frozen[path] or { '' } != pin { return error('final compile consumed an unfrozen input: ' + path) } }
	write_json(root + '/scope.json', {'historical_source_sha256': historical_source_pin,
		'historical_binary_sha256': historical_binary_pin, 'source_sha256': hash(root + '/source/launcher.v')!,
		'binary_sha256': hash(root + '/run-android-calculator')!,
		'build_root': os.abs_path(root), 'argv_root': root,
		'scope': 'fresh maintained launcher build; ten diagnostic setters removed; child argv and remaining environment behavior unchanged; no historical compiler reconstruction'})!
	mut manifest := map[string]string{}
	inventory(root, '', mut manifest)!
	write_json(root + '/sha256.json', manifest)!
	check(root)!
	println('MAPS CLEAN LAUNCHER BUILD PASS root=' + root + ' binary=' + hash(root + '/run-android-calculator')!)
}
fn check(root string) ! {
	mut actual := map[string]string{}
	inventory(root, '', mut actual)!
	equal_maps(actual, map_file(root + '/sha256.json')!)!
	trace_delta(os.read_file(root + '/source/trace200-launcher.v')!, os.read_file(root + '/source/launcher.v')!)!
	if hash(root + '/source/trace200-launcher.v')! != historical_source_pin { return error('wrong historical source reference') }
	pins := map_file(root + '/input-sha256.json')!
	for path, pin in pins { if hash(root + '/inputs/' + path.trim_left('/'))! != pin { return error('retained consumed input differs: ' + path) } }
	before := object(root + '/run-android-calculator-before.json')!
	done := object(root + '/run-android-calculator-receipt.json')!
	scope := map_file(root + '/scope.json')!
	expected_argv := compile_argv(scope['argv_root']!, 'run-android-calculator', scope['build_root']! + '/aarch64-linux-musl-gcc')
	if before['argv']!.as_array().map(it.str()) != expected_argv { return error('unexpected launcher compile argv') }
	resolutions := map_file(root + '/run-android-calculator-resolved-inputs.json')!
	paths := consumed_paths(root, 'run-android-calculator')!
	if resolutions.len != paths.len { return error('consumed input resolution count differs') }
	mut expected := map[string]string{}
	for path in paths {
		resolved := resolutions[path]!
		expected[resolved] = hash(root + '/inputs/' + resolved.trim_left('/'))!
	}
	discovery_paths := consumed_paths(root, 'discovery')!
	discovery_resolutions := map_file(root + '/discovery-resolved-inputs.json')!
	if discovery_paths.len != discovery_resolutions.len { return error('discovery input resolution count differs') }
	for path in discovery_paths {
		resolved := discovery_resolutions[path]!
		expected[resolved] = hash(root + '/inputs/' + resolved.trim_left('/'))!
	}
	equal_maps(expected, pins)!
	if scope['historical_source_sha256']! != historical_source_pin || scope['historical_binary_sha256']! != historical_binary_pin
		|| scope['source_sha256']! != hash(root + '/source/launcher.v')!
		|| scope['binary_sha256']! != hash(root + '/run-android-calculator')!
		|| pins[scope['build_root']! + '/source/launcher.v']! != scope['source_sha256']! { return error('launcher source/output scope differs') }
	for key in ['argv', 'started_utc', 'input_sha256'] { if json2.encode(before[key]!) != json2.encode(done[key]!) { return error('launcher receipt continuity differs: ' + key) } }
	if done['exit_code']!.int() != 0 || done['completed_utc']!.str() == ''
		|| done['output_sha256']!.str() != hash(root + '/run-android-calculator')!
		|| done['log_sha256']!.str() != hash(root + '/run-android-calculator.log')! { return error('incomplete launcher build receipt') }
	equal_maps(json2.decode[map[string]string](json2.encode(done['input_sha256']!))!, pins)!
	println('MAPS CLEAN LAUNCHER CHECK PASS inputs=' + pins.len.str())
}
fn self_test() ! {
	old := os.read_file(historical_source)!
	clean := os.read_file(launcher_source)!
	trace_delta(old, clean)!
	for changed in [clean.replace("'/usr/bin/run-android'", "'/usr/bin/other'"),
		clean.replace("fn main() {", "fn main() {\n os.setenv('VINIX_ANDROID_TRACE_TREE', '1', true)"),
		clean.replace('100 * time.millisecond', '200 * time.millisecond')] {
		mut rejected := false
		trace_delta(old, changed) or { rejected = true }
		assert rejected
	}
	println('MAPS CLEAN LAUNCHER SELF-TEST PASS exact ten removals; changed argv, trace setter and polling rejected')
}
fn main() {
	$if prod { panic('requires assertions; compile without -prod') }
	if os.file_name(os.executable()) == 'aarch64-linux-musl-gcc' { record_cc() or { eprintln(err); exit(1) }; return }
	if os.args.len == 2 && os.args[1] == '--self-test' { self_test() or { eprintln(err); exit(1) }; return }
	if os.args.len != 3 || os.args[1] !in ['build', 'check'] { eprintln('usage: maps-clean-launcher build|check FRESH_BUILD_ROOT'); exit(2) }
	if os.args[1] == 'build' { build(os.args[2]) or { eprintln(err); exit(1) } }
	else { check(os.args[2]) or { eprintln(err); exit(1) } }
}
