module artmterp

import os

// A complete synthetic 256-opcode table exercises the real expansion order.
// Expected assembly is specified independently of the template evaluator.
pub fn check_mterp(root string) ! {
	os.mkdir(root)!
	mut table := []string{}
	mut functions := []string{}
	mut expected := ['/* DO NOT EDIT: This file was generated by gen-mterp.py. */',
		'HEADER', 'ENTRY', 'BEGIN']
	mut helpers := map[string]string{}
	for i in 0 .. 256 {
		opcode := 'op_test_' + i.str()
		// Use standard V formatting here, independently of mterp's hex helper.
		table << '  V(0x${i:02x}, TEST_${i}, "test", fixture)'
		functions << '%def ${opcode}():'
		functions << match i {
			0 { '%  choose(is_object=True, helper="first")' }
			1 { '%  choose(reg="d1", helper="second")' }
			else { '%  choose()' }
		}
		helper := 'mterp_${opcode}_helper'
		branch := if i == 0 { 'OBJECT' } else if i == 1 { 'DOUBLE' } else { 'OTHER' }
		expected << ['/* ------------------------------ */', '    .balign MTERP_HANDLER_SIZE',
			'.L_${opcode}: /* 0x${i:02x} */', 'START ${i}', 'PRE', branch + ' ' + helper,
			'RAW $opcode $$opcode local', 'END', '']
		argument := if i == 0 { 'first' } else if i == 1 { 'second' } else { 'DEFAULT' }
		helpers[helper] = 'HELPER ${helper}\nFIELD ${argument} ${opcode}\nDONE ${helper}'
	}
	expected << ['    .balign MTERP_HANDLER_SIZE', 'FINISH']
	mut names := helpers.keys()
	names.sort()
	for name in names { expected << helpers[name] }
	expected << ['HELPER z_shared\nSHARED\nDONE z_shared', 'TAIL', 'FOOTER']
	common := '%def header():\nHEADER\n%def entry():\nENTRY\n' +
		'%def instruction_start():\nBEGIN\n%def instruction_end():\nFINISH\n' +
		'%def opcode_start():\nSTART $opnum\n%def opcode_end():\nEND\n' +
		'%def shared():\nSHARED\n%def opcode_pre():\n' +
		'%  add_helper(shared, "z_shared")\nPRE\n' +
		'%def helper_start(name):\nHELPER $name\n%def helper_end(name):\nDONE $name\n' +
		'%def helpers():\nTAIL\n%def footer():\nFOOTER\n' +
		'%def field(helper="DEFAULT"):\nFIELD $helper $opcode\n' +
		'%def choose(is_object=False, reg="x0", helper="DEFAULT", opcode="local"):\n' +
		'%  label = add_helper(lambda: field(helper))\n' +
		'%  if is_object:\nOBJECT $label\n%  elif reg.startswith("d"):\n' +
		'DOUBLE $label\n%  else:\nOTHER $label\n%  #endif\n' +
		r'RAW $$opcode $$$opcode ${opcode}' + '\n'
	first := root + '/a.S'
	second := root + '/b.S'
	os.write_file(first, common)!
	os.write_file(second, functions.join('\n') + '\n')!
	opcodes := table.join('\n') + '\n  V(kFormat)\n  V(other, arguments, ignored)\n'
	wanted := expected.join('\n') + '\n'
	actual := mterp(opcodes, [second, first])!
	os.write_file(root + '/expected.S', wanted)!
	os.write_file(root + '/actual.S', actual)!
	if actual != wanted { return error('complete synthetic interpreter differs from independent expected assembly') }
	os.write_file(root + '/opcodes.h', opcodes)!
	for bad in ['', opcodes.replace('0x00, TEST_0', '0x01, TEST_0'),
		opcodes + '  V(0x00, EXTRA, "extra", fixture)\n'] {
		if _ := mterp(bad, [first, second]) { return error('invalid opcode table accepted') }
	}
	mutations := [
		common.replace('HEADER', '$missing'),
		common.replace('HEADER', '%  missing()'),
		common.replace('HEADER', '%  header()'),
		common + '%def header():\nDUPLICATE\n',
		common.replace('choose(is_object=False, reg="x0", helper="DEFAULT", opcode="local")', 'choose()'),
		common.replace('PRE', '%  field(unknown="bad")'),
	]
	for i, mutation in mutations {
		path := root + '/bad-${i}.S'
		os.write_file(path, mutation)!
		if _ := mterp(opcodes, [path, second]) { return error('invalid template mutation accepted: ${i}') }
	}
	println('ART-MTERP-CHECK-PASS complete golden expansion, branches, captures, globals, escapes, helper order, invalid inputs')
}
