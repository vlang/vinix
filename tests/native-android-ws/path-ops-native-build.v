}

fn write_json[T](path string, value T) ! {
	os.mkdir_all(os.dir(path))!
	os.write_file(path, json2.encode(value, prettify: true) + '\n')!
}

fn clone_file(from string, to string) ! {
	assert !os.exists(to) && !os.is_link(to), to
	os.mkdir_all(os.dir(to))!
	checked(['cp', '-c', os.real_path(from), to])!
}

// Keep every existing generated byte, including qualified JNI additions.
// Derive only the two new wrappers from the appended native bindings.
fn wrapper(old string, old_bindings string, bindings string, path string) string {
	assert old_bindings.ends_with('\n') && bindings.starts_with(old_bindings)
	addition := bindings[old_bindings.len..]
	assert addition.ends_with('\n') && addition.split_into_lines().len == 2
	lines := addition.split_into_lines()
	parts := lines[0].split('|')
	assert parts.len == 3 && parts[0] == 'android/graphics/Path'
	assert parts[1] in ['native_op', 'native_op(Landroid/graphics/Path;Landroid/graphics/Path;JIJII)J']
	assert parts[2] == 'return ws_path_op(p2,p3,p4,p5,p6)'
	empty := lines[1].split('|')
	assert empty.len == 3 && empty[0] == 'android/graphics/Path'
	assert empty[1] in ['native_is_empty', 'native_is_empty(Landroid/graphics/Path;J)Z']
	assert empty[2] == 'return u8(ws_path_is_empty(p1))'
	assert path.count('.method private static native native_op(Landroid/graphics/Path;Landroid/graphics/Path;JIJII)J\n') == 1
	assert path.count('.method private static native native_is_empty(Landroid/graphics/Path;J)Z\n') == 1
	assert !old.contains(op_symbol) && !old.contains('fn ws_path_native_op(')
	assert !old.contains(empty_symbol) && !old.contains('fn ws_path_native_is_empty(')
	return "\n@[export: '${op_symbol}']\nfn ws_path_native_op(e voidptr, this voidptr, p0 voidptr, p1 voidptr, p2 i64, p3 i32, p4 i64, p5 i32, p6 i32) i64 {\n    unsafe {\n ${parts[2]}\n }\n}\n\n@[export: '${empty_symbol}']\nfn ws_path_native_is_empty(e voidptr, this voidptr, p0 voidptr, p1 i64) u8 {\n    unsafe {\n ${empty[2]}\n }\n}\n"
}

fn reference(pins map[string]string, relative string, target string) ! {
