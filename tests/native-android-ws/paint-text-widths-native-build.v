}

fn write_json[T](path string, value T) ! {
	os.mkdir_all(os.dir(path))!
	os.write_file(path, json2.encode(value, prettify: true) + '\n')!
}

fn clone_file(from string, to string) ! {
	assert !os.exists(to) && !os.is_link(to), to
	os.mkdir_all(os.dir(to))!
	checked(['cp', '-c', os.real_path(from), to])!
}

// Preserve every existing generated byte; derive only the two new wrappers.
fn wrapper(old string, old_bindings string, bindings string, descriptor string) string {
 anchor := 'android/graphics/Paint|measureText([CII)F|return ws_measure_text(e,this,p0,p1,p2,true)\n'
 string_body := 'return ws_text_widths(e,this,p0,p1,p2,p3,false)'
 array_body := 'return ws_text_widths(e,this,p0,p1,p2,p3,true)'
 added := 'android/graphics/Paint|getTextWidths(Ljava/lang/String;II[F)I|' + string_body + '\nandroid/graphics/Paint|getTextWidths([CII[F)I|' + array_body + '\n'
 assert old_bindings.count(anchor) == 1
 assert bindings == old_bindings.replace(anchor, anchor + added)
 assert descriptor.count('.method public native getTextWidths(Ljava/lang/String;II[F)I\n') == 1
 assert descriptor.count('.method public native getTextWidths([CII[F)I\n') == 1
 assert !old.contains(string_symbol) && !old.contains(array_symbol)
 return old + "\n@[export: '${string_symbol}']\nfn ws_paint_text_widths_string(e voidptr, this voidptr, p0 voidptr, p1 i32, p2 i32, p3 voidptr) i32 {\n    unsafe {\n ${string_body}\n }\n}\n\n@[export: '${array_symbol}']\nfn ws_paint_text_widths_array(e voidptr, this voidptr, p0 voidptr, p1 i32, p2 i32, p3 voidptr) i32 {\n    unsafe {\n ${array_body}\n }\n}\n"
}

// Admit one contiguous routine insertion; all existing font bytes must survive.
fn derived_fonts(old string, updated string) string {
 anchor := 'fn ws_font_ref(font &WsFont) {\n'
 assert old.count(anchor) == 1 && updated.count(anchor) == 1
 at := old.index(anchor) or { panic('missing font routine anchor') }
 prefix := old[..at]
 suffix := old[at..]
 assert updated.len > old.len && updated.starts_with(prefix) && updated.ends_with(suffix)
 added := updated[prefix.len..updated.len - suffix.len]
 assert added.count('fn ') == 1
 assert added.count('fn ws_text_widths(e voidptr, paint voidptr, text voidptr, start i32, limit i32, widths voidptr, array bool) i32 {\n') == 1
 assert added.ends_with('}\n\n')
 return updated
}

