fn hash(path string) !string {
	mut f := os.open(path)!
	defer { f.close() }
	mut sum := sha256.new()
	mut buffer := []u8{len: 1024 * 1024}
	for {
		n := f.read(mut buffer) or {
			if err is os.Eof { break }
			return err
		}
		if n == 0 { break }
		sum.write(buffer[..n])!
	}
	return sum.sum([]u8{}).hex()
}

fn all_files(root string) ![]string {
	assert os.lstat(root)!.get_filetype() == .directory, root
	mut files := []string{}
	for name in os.ls(root)! {
		path := root + '/' + name
		match os.lstat(path)!.get_filetype() {
			.directory { files << all_files(path)! }
			.regular { files << path }
			else { return error('nonregular build entry: ' + path) }
		}
	}
	files.sort()
	return files
}

fn checked(argv []string) !string {
	r := os.exec(argv)
	if r.exit_code != 0 { return error(argv.str() + '\n' + r.output) }
	return r.output
}

fn write_json[T](path string, value T) ! {
	os.mkdir_all(os.dir(path))!
	os.write_file(path, json2.encode(value, prettify: true) + '\n')!
}

fn clone_file(from string, to string) ! {
	assert !os.exists(to) && !os.is_link(to), to
	os.mkdir_all(os.dir(to))!
	checked(['cp', '-c', os.real_path(from), to])!
}

// Preserve every existing generated byte; derive one new draw wrapper.
fn wrapper(old string, old_bindings string, bindings string, descriptor string) string {
	anchor := 'android/graphics/drawable/NinePatchDrawable|nativeGetIntrinsicHeight|return if p0 == 0 { -1 } else { (&WsBitmap(p0)).height }\n'
	body := "previous := ws_canvas_enter(e,p1,get_long(e,p1,c'android/atl/GskCanvas',c'snapshot')); defer { ws_canvas_leave(previous) }; if pending(e) { return }; ws_draw_bitmap_paint(p0,p2,p3,p4,p5,p6)"
	added := 'android/graphics/drawable/NinePatchDrawable|nativeDraw(JLandroid/graphics/Canvas;IIIIJ)V|' + body + '\n'
	assert old_bindings.count(anchor) == 1
	assert bindings == old_bindings.replace(anchor, anchor + added)
	assert descriptor.count('.method private static native nativeDraw(JLandroid/graphics/Canvas;IIIIJ)V\n') == 1
	assert !old.contains(draw_symbol)
	return old + "\n@[export: '${draw_symbol}']\nfn ws_nine_patch_draw(e voidptr, c voidptr, p0 i64, p1 voidptr, p2 i32, p3 i32, p4 i32, p5 i32, p6 i64) {\n    unsafe {\n ${body}\n }\n}\n"
}

fn reference(pins map[string]string, relative string, target string) ! {
