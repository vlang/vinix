module main

import os
import strings

fn word(data []u8, at int) u32 {
	return u32(data[at]) | u32(data[at + 1]) << 8 | u32(data[at + 2]) << 16 | u32(data[at + 3]) << 24
}

fn main() {
	if os.args.len != 4 { panic('usage: generate_firmware.v rtl8168g-2.fw rtl8168g-3.fw output.v') }
	mut out := strings.new_builder(20000)
	out.writeln('// Copyright © 2011-2013, Realtek Semiconductor Corporation')
	out.writeln('// Permission is hereby granted for the distribution of this firmware')
	out.writeln('// data in hexadecimal or equivalent format, provided this copyright')
	out.writeln('// notice is accompanying it.')
	out.writeln('// Generated by tests/rtl8169/generate_firmware.v; see its README.md.')
	out.writeln('module rtl8169\n')
	for i, name in ['firmware_g', 'firmware_gu'] {
		data := os.read_bytes(os.args[i + 1]) or { panic(err) }
		if data.len < 49 || word(data, 0) != 0 { panic('invalid firmware header') }
		mut checksum := u8(0)
		for byte in data { checksum += byte }
		if checksum != 0 { panic('invalid firmware checksum') }
		start := int(word(data, 36))
		count := int(word(data, 40))
		if start < 49 || start > data.len || count < 1 || count > (data.len - start) / 4 {
			panic('invalid firmware extent')
		}
		out.writeln('const ${name} = [')
		for index in 0 .. count {
			if index % 6 == 0 { out.write_string('\t') }
			value := word(data, start + index * 4)
			out.write_string('u32(0x${value:08x}),')
			if index % 6 == 5 || index == count - 1 { out.writeln('') }
			else { out.write_string(' ') }
		}
		out.writeln(']!')
		if i == 0 { out.writeln('') }
	}
	os.write_file(os.args[3], out.str()) or { panic(err) }
}
