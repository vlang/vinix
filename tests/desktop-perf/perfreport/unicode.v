struct RuneRange {
	start int
	end   int
}

fn printable(ch rune) bool {
	mut low := 0
	mut high := nonprint_ranges.len
	for low < high {
		mid := (low + high) / 2
		item := nonprint_ranges[mid]
		if int(ch) < item.start {
			high = mid
		} else if int(ch) > item.end {
			low = mid + 1
		} else {
			return false
		}
	}
	return true
}

fn decimal(ch rune) int {
	for zero in decimal_zeros {
		if int(ch) >= zero && int(ch) < zero + 10 { return int(ch) - zero }
	}
	return -1
}

fn number_space(ch rune) bool {
	return int(ch) in [9, 10, 11, 12, 13, 32, 0x85, 0xa0, 0x1680, 0x2028, 0x2029, 0x202f, 0x205f,
		0x3000] || (ch >= 0x2000 && ch <= 0x200a)
}

fn normalize_number(text string, integral bool) !string {
	runes := text.runes()
	mut first := 0
	mut last := runes.len
	for first < last && number_space(runes[first]) { first++ }
	for last > first && number_space(runes[last - 1]) { last-- }
	if first == last { return error('empty number') }
	mut result := ''
	for index in first .. last {
		ch := runes[index]
		digit := decimal(ch)
		if digit >= 0 {
			result += u8(digit + 48).ascii_str()
		} else if ch == `_` {
			if index == first || index + 1 == last || decimal(runes[index - 1]) < 0 || decimal(runes[index + 1]) < 0 {
				return error('invalid digit separator')
			}
		} else if ch < 128 {
			result += ch.str()
		} else {
			return error('invalid number')
		}
	}
	mut index := if result[0] in [`+`, `-`] { 1 } else { 0 }
	if index == result.len { return error('missing digits') }
	if !integral && result[index..].to_lower() in ['nan', 'inf', 'infinity'] { return result }
	mut digits := 0
	for index < result.len && result[index].is_digit() {
		digits++
		index++
	}
	if !integral && index < result.len && result[index] == `.` {
		index++
		for index < result.len && result[index].is_digit() {
			digits++
			index++
		}
	}
	if digits == 0 { return error('missing digits') }
	if !integral && index < result.len && result[index] in [`e`, `E`] {
		index++
		if index < result.len && result[index] in [`+`, `-`] { index++ }
		exponent := index
		for index < result.len && result[index].is_digit() { index++ }
		if index == exponent { return error('missing exponent') }
	}
	if index != result.len { return error('invalid decimal number') }
	return result
}
