fn module_word(ch rune) bool {
	mut low := 0
	mut high := module_word_ranges.len
	for low < high {
		mid := (low + high) / 2
		row := module_word_ranges[mid]
		if u32(ch) < row.first {
			high = mid
		} else if u32(ch) > row.last {
			low = mid + 1
		} else {
			return true
		}
	}
	return false
}

fn module_space(ch rune) bool {
	return ch in [`\t`, `\n`, `\v`, `\f`, `\r`, ` `, rune(0x85), rune(0xa0), rune(0x1680),
		rune(0x2028), rune(0x2029), rune(0x202f), rune(0x205f), rune(0x3000)] || (ch >= 0x1c && ch <= 0x1f) || (ch >= 0x2000 && ch <= 0x200a)
}

fn module_upper(text string) string {
	mut result := ''
	for ch in text.runes() {
		if u32(ch) in module_upper_expansions {
			result += module_upper_expansions[u32(ch)]
			continue
		}
		mut translated := ch
		for row in module_upper_ranges {
			if u32(ch) >= row.first && u32(ch) <= row.last && (u32(ch) - row.first) % row.step == 0 {
				translated = rune(i64(ch) + row.delta)
				break
			}
		}
		result += translated.str()
	}
	return result
}
