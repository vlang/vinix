// Native Apple Foundation measurement. Regenerate on the recorded macOS build:
// v -gc none -cc clang -o build/ios/fortnite/character-set-native/data-generator tests/ios/character-set-data.v
// build/ios/fortnite/character-set-native/data-generator compat/ios/runner/ns_character_set_data.c.v
module main

import crypto.sha256
import os
import strings

#flag -framework Foundation
#include <objc/runtime.h>
#include <dlfcn.h>

fn C.objc_getClass(&char) voidptr
fn C.sel_registerName(&char) voidptr
fn C.dlsym(voidptr, &char) voidptr

type CharacterSetDataSend = fn (u64, u64) u64
type CharacterSetDataMember = fn (u64, u64, u32) bool

fn native_command(args []string) string {
	mut p := os.new_process(args[0])
	p.set_args(args[1..])
	p.set_redirect_stdio_merged()
	p.run()
	result := p.stdout_slurp()
	p.wait()
	assert p.code == 0
	p.close()
	return result.trim_space()
}

fn main() {
	assert os.args.len == 2, 'supply output .c.v path'
	assert os.user_os() == 'macos', 'requires Apple Foundation'
	symbol := C.dlsym(voidptr(-2), c'objc_msgSend')
	assert symbol != unsafe { nil }
	send := unsafe { CharacterSetDataSend(symbol) }
	member := unsafe { CharacterSetDataMember(symbol) }
	selector := u64(C.sel_registerName(c'longCharacterIsMember:'))
	pool := send(u64(C.objc_getClass(c'NSAutoreleasePool')), u64(C.sel_registerName(c'new')))
	version := native_command(['/usr/bin/sw_vers', '-productVersion'])
	build := native_command(['/usr/bin/sw_vers', '-buildVersion'])
	arch := native_command(['/usr/bin/uname', '-m'])
	mut source := strings.new_builder(100000)
	source.writeln('module main\n')
	source.writeln('// Generated by tests/ios/character-set-data.v using Apple Foundation.')
	source.writeln('// Native macOS ${version} (${build}), ${arch}; exhaustive domain U+000000..U+10FFFF.')
	source.writeln('// Each SHA-256 covers 139264 little-bit-order bitmap bytes; Unicode tables follow this host version.')
	source.writeln('// Reproduce with the generator command recorded in its source. Do not edit by hand.\n')
	source.writeln('fn ns_character_set_predefined_fill(name string, bits &u8) bool {')
	source.writeln('\tmatch name {')
	for name in ['alphanumericCharacterSet', 'decimalDigitCharacterSet', 'whitespaceCharacterSet',
		'URLQueryAllowedCharacterSet', 'URLHostAllowedCharacterSet', 'URLPathAllowedCharacterSet',
		'illegalCharacterSet', 'controlCharacterSet'] {
		factory := u64(C.sel_registerName(name.str))
		immutable := send(u64(C.objc_getClass(c'NSCharacterSet')), factory)
		mutable := send(u64(C.objc_getClass(c'NSMutableCharacterSet')), factory)
		assert immutable != 0 && mutable != 0
		mut bits := []u8{len: 0x110000 / 8}
		mut ranges := []u32{}
		mut start := u32(0)
		mut in_range := false
		mut count := u32(0)
		for point in u32(0) .. u32(0x110000) {
			has := member(immutable, selector, point)
			assert has == member(mutable, selector, point), '${name} immutable/mutable differ at ${point.hex()}'
			if has {
				bits[int(point >> 3)] |= u8(1 << (point & 7))
				count++
				if !in_range {
					start = point
					in_range = true
				}
			} else if in_range {
				ranges << start
				ranges << point
				in_range = false
			}
		}
		if in_range {
			ranges << start
			ranges << u32(0x110000)
		}
		digest := sha256.sum(bits).hex()
		println('${name} members=${count} ranges=${ranges.len / 2} bitmap_sha256=${digest}')
		source.writeln("\t\t'${name}' {")
		source.writeln('\t\t\t// ${count} members, ${ranges.len / 2} ranges; bitmap SHA-256 ${digest}')
		for i := 0; i < ranges.len; i += 2 {
			source.writeln('\t\t\tns_character_set_set_range(bits, u32(0x${ranges[i].hex()}), u32(0x${(ranges[i + 1] - ranges[i]).hex()}), true)')
		}
		source.writeln('\t\t\treturn true\n\t\t}')
	}
	source.writeln('\t\telse { return false }\n\t}\n}')
	os.write_file(os.args[1], source.str())!
	println('native macOS ${version} (${build}) ${arch}')
	println('output_sha256=' + sha256.sum(os.read_bytes(os.args[1])!).hex())
	send(pool, u64(C.sel_registerName(c'drain')))
}
