module main

import os
import json2
import strings
import crypto.sha256

struct Requirement {
	flags         u32
	parameter     string
	target        string
	protocol_name string
}

struct Declaration {
	name         string
	flags        u32
	associated   string
	signature    []Requirement
	requirements []u32
	defaults     []bool
}

fn put32(mut bytes []u8, at int, value u32) {
	for i in 0 .. 4 { bytes[at + i] = u8(value >> u32(i * 8)) }
}

fn relative(mut bytes []u8, at int, target int) { put32(mut bytes, at, u32(i32(target - at))) }

fn text_offset(mut bytes []u8, mut pool map[string]int, value string) int {
	if at := pool[value] { return at }
	at := bytes.len
	for b in value.bytes() { bytes << b }
	bytes << u8(0)
	pool[value] = at
	return at
}

fn main() {
	root := os.real_path(os.dir(@FILE) + '/../..')
	path := root + '/tests/ios/string-protocol-schema.json'
	source := os.read_file(path)!
	declarations := json2.decode[[]Declaration](source)!
	assert declarations.len == 20 && declarations[0].name == 'StringProtocol' && declarations[0].signature.len == 20 && declarations[0].requirements.len == 26
	mut offsets := []int{}
	mut cells := []int{}
	mut names := map[string]int{}
	mut size := 64
	for i, d in declarations {
		assert d.requirements.len == d.defaults.len
		offsets << size
		names[d.name] = i
		size += 24 + d.signature.len * 12 + d.requirements.len * 8
	}
	size = (size + 7) & ~7
	for _ in declarations {
		cells << size
		size += 8
	}
	mut bytes := []u8{len: size}
	mut pool := map[string]int{}
	mut defaults := []int{}
	relative(mut bytes, 0, cells[0] + 1)
	relative(mut bytes, 4, 33)
	put32(mut bytes, 12, 0x20008)
	put32(mut bytes, 16, 0x1001b)
	for i, d in declarations {
		at := offsets[i]
		put32(mut bytes, at, d.flags)
		relative(mut bytes, at + 4, 48)
		text := text_offset(mut bytes, mut pool, d.name)
		relative(mut bytes, at + 8, text)
		put32(mut bytes, at + 12, u32(d.signature.len))
		put32(mut bytes, at + 16, u32(d.requirements.len))
		if d.associated != '' {
			text2 := text_offset(mut bytes, mut pool, d.associated)
			relative(mut bytes, at + 20, text2)
		}
		for j, r in d.signature {
			field := at + 24 + j * 12
			put32(mut bytes, field, r.flags)
			parameter := text_offset(mut bytes, mut pool, r.parameter)
			relative(mut bytes, field + 4, parameter)
			if r.protocol_name != '' {
				index := names[r.protocol_name] or { panic(r.protocol_name) }
				relative(mut bytes, field + 8, cells[index] + 1)
			} else {
				target := text_offset(mut bytes, mut pool, r.target)
				relative(mut bytes, field + 8, target)
			}
		}
		for j, flags in d.requirements {
			field := at + 24 + d.signature.len * 12 + j * 8
			put32(mut bytes, field, flags)
			if d.defaults[j] { defaults << field + 4 }
		}
	}
	module_name := text_offset(mut bytes, mut pool, 'Swift')
	relative(mut bytes, 56, module_name)
	for bytes.len % 8 != 0 { bytes << u8(0) }
	pattern := bytes.len
	bytes << []u8{len: 27 * 8}
	relative(mut bytes, 8, pattern)
	mut output := strings.new_builder(40000)
	output.writeln('// Generated by tests/ios/string-protocol-schema.v; native macOS 26.5 declaration schema.\n// Source SHA256: ' + sha256.sum(source.bytes()).hex() + '\nmodule main\n\nconst swift_string_protocol_schema_words = [')
	for i := 0; i < bytes.len; i += 8 {
		mut word := u64(0)
		for j in 0 .. 8 { word |= u64(bytes[i + j]) << u32(j * 8) }
		output.writeln('\tu64(0x' + word.hex() + '),')
	}
	output.writeln(']!\n\nconst swift_string_protocol_schema_nodes = [')
	for i, d in declarations {
		output.writeln("\tSwiftStringProtocolNode{'" + d.name + "', " + offsets[i].str() + ', ' + cells[i].str() + '},')
	}
	output.writeln(']!\n\nconst swift_string_protocol_schema_defaults = [')
	for field in defaults { output.writeln('\tu64(' + field.str() + '),') }
	output.writeln(']!')
	output.writeln('\nconst swift_string_protocol_schema_pattern_offset = u64(' + pattern.str() + ')')
	generated := root + '/compat/ios/runner/swift_string_protocol_schema.c.v'
	if os.args.len > 1 && os.args[1] == 'check' {
		assert os.read_file(generated)! == output.str()
	} else {
		os.write_file(generated, output.str())!
	}
	println('StringProtocol schema: ' + declarations.len.str() + ' declarations, ' + bytes.len.str() + ' bytes and ' + defaults.len.str() + ' explicit diagnostic default references; generated bytes verified')
}
