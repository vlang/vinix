module main

import os
import strconv
import crypto.sha256
import json2
import strings

struct NfcComposition {
	first  u32
	second u32
	scalar u32
	key    u64
}

fn main() {
	root := os.real_path(os.dir(@FILE) + '/../..')
	directory := root + '/build/ios/unicode-nfc'
	os.mkdir_all(directory)!
	manifest_path := root + '/tests/ios/unicode-nfc.json'
	mut manifest := map[string]string{}
	if os.exists(manifest_path) {
		manifest = json2.decode[map[string]string](os.read_file(manifest_path)!)!
	}
	for name in ['UnicodeData.txt', 'CompositionExclusions.txt', 'NormalizationTest.txt', 'LICENSE.txt']! {
		path := directory + '/' + name
		if !os.exists(path) {
			url := if name == 'LICENSE.txt' {
				'https://www.unicode.org/license.txt'
			} else {
				'https://www.unicode.org/Public/17.0.0/ucd/' + name
			}
			mut process := os.new_process('/usr/bin/curl')
			process.set_args(['--fail', '--location', '--silent', '--show-error', url, '-o', path])
			process.run()
			process.wait()
			code := process.code
			process.close()
			assert code == 0
		}
		hash := sha256.sum(os.read_bytes(path)!).hex()
		if expected := manifest[name] {
			assert hash == expected, name
		} else {
			assert os.args.len == 2 && os.args[1] == 'pin'
			manifest[name] = hash
		}
	}
	if os.args.len == 2 && os.args[1] == 'pin' {
		os.write_file(manifest_path, json2.encode(manifest, prettify: true) + '\n')!
	}
	mut classes := map[u32]u32{}
	mut decompositions := map[u32][]u32{}
	for line in (os.read_file(directory + '/UnicodeData.txt')!).split_into_lines() {
		fields := line.split(';')
		assert fields.len == 15
		scalar := u32(strconv.parse_uint(fields[0], 16, 32)!)
		class := u32(strconv.parse_uint(fields[3], 10, 8)!)
		if class != 0 { classes[scalar] = class }
		if fields[5] != '' && !fields[5].starts_with('<') {
			mut values := []u32{}
			for word in fields[5].fields() { values << u32(strconv.parse_uint(word, 16, 32)!) }
			assert values.len in [1, 2]!
			decompositions[scalar] = values
		}
	}
	mut exclusions := map[u32]bool{}
	for line in (os.read_file(directory + '/CompositionExclusions.txt')!).split_into_lines() {
		word := line.all_before('#').trim_space()
		if word != '' { exclusions[u32(strconv.parse_uint(word, 16, 32)!)] = true }
	}
	mut output := strings.new_builder(140000)
	output.writeln('// Generated by tests/ios/unicode-nfc.v from Unicode 17.0.0; do not edit.')
	for line in (os.read_file(directory + '/LICENSE.txt')!).split_into_lines() {
		output.writeln(('// ' + line).trim_right(' '))
	}
	output.writeln('module main\n\nconst swift_nfc_classes = [')
	mut keys := classes.keys()
	keys.sort()
	for scalar in keys {
		output.writeln('\tu64(0x' + ((u64(scalar) << 8) | u64(classes[scalar])).hex() + '),')
	}
	output.writeln(']!\n\nconst swift_nfc_decompositions = [')
	keys = decompositions.keys()
	keys.sort()
	mut compositions := []NfcComposition{}
	for scalar in keys {
		values := decompositions[scalar]
		second := if values.len == 2 { values[1] } else { u32(0) }
		output.writeln('\tSwiftNfcDecomposition{0x' + scalar.hex() + ', 0x' + values[0].hex() + ', 0x' + second.hex() + '},')
		if second != 0 && scalar !in exclusions && classes[values[0]] == 0 {
			compositions << NfcComposition{values[0], second, scalar, (u64(values[0]) << 21) | second}
		}
	}
	compositions.sort(a.key < b.key)
	output.writeln(']!\n\nconst swift_nfc_compositions = [')
	for value in compositions {
		output.writeln('\tSwiftNfcDecomposition{0x' + value.scalar.hex() + ', 0x' + value.first.hex() + ', 0x' + value.second.hex() + '},')
	}
	output.writeln(']!')
	path := root + '/compat/ios/runner/swift_unicode_nfc_data.c.v'
	source := output.str()
	if os.args.len == 2 && os.args[1] == 'check' {
		assert os.read_file(path)! == source
	} else {
		os.write_file(path, source)!
	}
	println('Unicode NFC: ' + classes.len.str() + ' classes, ' + decompositions.len.str() + ' canonical decompositions, ' + compositions.len.str() + ' composition pairs; pinned data and generated source verified')
}
