module main

import os
import strconv
import crypto.sha256
import json2
import strings

// Pin the independent segmentation test corpus along with all property inputs.
fn main() {
	root := os.real_path(os.dir(@FILE) + '/../..')
	directory := root + '/build/ios/unicode-grapheme'
	os.mkdir_all(directory)!
	manifest_path := root + '/tests/ios/unicode-grapheme.json'
	mut manifest := map[string]string{}
	if os.exists(manifest_path) {
		manifest = json2.decode[map[string]string](os.read_file(manifest_path)!)!
	}
	for name in ['auxiliary/GraphemeBreakProperty.txt', 'emoji/emoji-data.txt',
		'DerivedCoreProperties.txt', 'auxiliary/GraphemeBreakTest.txt', 'LICENSE.txt']! {
		path := directory + '/' + os.file_name(name)
		if !os.exists(path) {
			url := if name == 'LICENSE.txt' {
				'https://www.unicode.org/license.txt'
			} else {
				'https://www.unicode.org/Public/17.0.0/ucd/' + name
			}
			mut p := os.new_process('/usr/bin/curl')
			p.set_args(['--fail', '--location', '--silent', '--show-error', url, '-o', path])
			p.run()
			p.wait()
			code := p.code
			p.close()
			assert code == 0
		}
		hash := sha256.sum(os.read_bytes(path)!).hex()
		if expected := manifest[name] {
			assert hash == expected, name
		} else {
			assert os.args.len == 2 && os.args[1] == 'pin'
			manifest[name] = hash
		}
	}
	if os.args.len == 2 && os.args[1] == 'pin' {
		os.write_file(manifest_path, json2.encode(manifest, prettify: true) + '\n')!
	}
	mut properties := []u8{len: 0x110000}
	classes := {
		'CR':                 u8(1)
		'LF':                 2
		'Control':            3
		'Extend':             4
		'ZWJ':                5
		'Regional_Indicator': 6
		'Prepend':            7
		'SpacingMark':        8
		'L':                  9
		'V':                  10
		'T':                  11
		'LV':                 12
		'LVT':                13
	}
	indic := {
		'Consonant': u8(32)
		'Extend':    64
		'Linker':    96
	}
	for name in ['GraphemeBreakProperty.txt', 'emoji-data.txt', 'DerivedCoreProperties.txt']! {
		for raw in (os.read_file(directory + '/' + name)!).split_into_lines() {
			line := raw.all_before('#').trim_space()
			if line == '' { continue }
			fields := line.split(';').map(it.trim_space())
			assert fields.len >= 2
			mut bits := u8(0)
			if name == 'GraphemeBreakProperty.txt' {
				bits = classes[fields[1]] or { panic(fields[1]) }
			} else if name == 'emoji-data.txt' {
				if fields[1] != 'Extended_Pictographic' { continue }
				bits = 16
			} else {
				if fields[1] != 'InCB' { continue }
				assert fields.len >= 3
				bits = indic[fields[2]] or { panic(fields[2]) }
			}
			ends := fields[0].split('..')
			first := int(strconv.parse_uint(ends[0], 16, 21)!)
			last := int(strconv.parse_uint(ends.last(), 16, 21)!)
			assert first <= last && last < properties.len
			for i in first .. last + 1 { properties[i] |= bits }
		}
	}
	mut output := strings.new_builder(100000)
	output.writeln('// Generated by tests/ios/unicode-grapheme.v from Unicode 17.0.0; do not edit.')
	for line in (os.read_file(directory + '/LICENSE.txt')!).split_into_lines() {
		output.writeln(('// ' + line).trim_right(' '))
	}
	output.writeln('module main\n\n// Packed inclusive ranges: first bits 0..20, last 21..41, properties 42..48.\nconst swift_grapheme_ranges = [')
	mut first := 0
	mut ranges := 0
	for first < properties.len {
		mut last := first
		for last + 1 < properties.len && properties[last + 1] == properties[first] { last++ }
		if properties[first] != 0 {
			word := u64(first) | (u64(last) << 21) | (u64(properties[first]) << 42)
			output.writeln('\tu64(0x' + word.hex() + '),')
			ranges++
		}
		first = last + 1
	}
	output.writeln(']!')
	path := root + '/compat/ios/runner/swift_unicode_grapheme_data.c.v'
	source := output.str()
	if os.args.len == 2 && os.args[1] == 'check' {
		assert os.read_file(path)! == source
	} else {
		os.write_file(path, source)!
	}
	println('Unicode graphemes: ' + ranges.str() + ' merged property ranges; pinned Unicode 17 data, boundary corpus and generated source verified')
}
