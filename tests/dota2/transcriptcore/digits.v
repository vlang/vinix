module transcriptcore

// Decimal ranges from Python Unicode 13.0.0; each starts a ten-digit run.
const decimal_starts = [rune(0x30), rune(0x660), rune(0x6f0), rune(0x7c0), rune(0x966), rune(0x9e6),
	rune(0xa66), rune(0xae6), rune(0xb66), rune(0xbe6), rune(0xc66), rune(0xce6), rune(0xd66),
	rune(0xde6), rune(0xe50), rune(0xed0), rune(0xf20), rune(0x1040), rune(0x1090), rune(0x17e0),
	rune(0x1810), rune(0x1946), rune(0x19d0), rune(0x1a80), rune(0x1a90), rune(0x1b50), rune(0x1bb0),
	rune(0x1c40), rune(0x1c50), rune(0xa620), rune(0xa8d0), rune(0xa900), rune(0xa9d0), rune(0xa9f0),
	rune(0xaa50), rune(0xabf0), rune(0xff10), rune(0x104a0), rune(0x10d30), rune(0x11066),
	rune(0x110f0), rune(0x11136), rune(0x111d0), rune(0x112f0), rune(0x11450), rune(0x114d0),
	rune(0x11650), rune(0x116c0), rune(0x11730), rune(0x118e0), rune(0x11950), rune(0x11c50),
	rune(0x11d50), rune(0x11da0), rune(0x16a60), rune(0x16b50), rune(0x1d7ce), rune(0x1d7d8),
	rune(0x1d7e2), rune(0x1d7ec), rune(0x1d7f6), rune(0x1e140), rune(0x1e2f0), rune(0x1e950),
	rune(0x1fbf0)]

fn decimal_digit(ch rune) int {
	for start in decimal_starts { if ch >= start && ch < start + 10 { return int(ch - start) } }
	return -1
}
