@[has_globals]
module gpustage

import hosttest
import os
import policyhost
import sourcecommand

fn command(argv []string, env map[string]string, limit int) !string {
	result := sourcecommand.capture(argv, env, -1, limit, policyhost.command_interrupted)!
	if result.status != 0 { return error('command failed: ' + argv.join(' ') + '\n' + result.stderr) }
	return result.stdout
}

pub fn stage(destination string, compiler string, v string, revision string) ! {
	guard := policyhost.own_commands(); defer { guard.close() }
	root := os.real_path(@DIR + '/../../..')
	output := hosttest.module_resolve(destination)!
	if output == root || output == root + '/desktop' { return error('Use a build staging directory for generated presenter artifacts') }
	os.mkdir_all(output)!
	mut env := os.environ()
	if v != '' {
		candidate := if os.is_dir(v) { v + '/v' } else { v }
		env['V'] = if os.is_file(candidate) { os.real_path(candidate) } else { os.find_abs_path_of_executable(candidate) or { candidate } }
	}
	commit := command(['git', '-C', root, 'rev-parse', revision + '^{commit}'], env, 4096)!.trim_space()
	work := sourcecommand.temporary('vinix-host-gpu')!
	defer { os.rmdir_all(work) or { eprintln(err) } }
	// Freeze the native generator as well as the presenter at the requested Git
	// revision. The public generator front and its complete closure are V/Shell.
	trees := ['desktop/gpucore', 'tests/linuxkpi/hosttest', 'tests/qemu-core/fixturehost', 'tests/host-policy/policyhost']
	mut paths := []string{}
	for tree in trees {
		paths << command(['git', '-C', root, 'ls-tree', '-rz', '--name-only', commit, tree], env, 1024 * 1024)!.split('\x00').filter(it != '' && !it.ends_with('_test.v'))
	}
	paths << ['build-support/compile-v-module', 'build-support/run-v-tool.sh', 'build-support/find-v.sh', 'tests/linuxkpi/generate_module.v', 'tests/linuxkpi/fixturehost', 'tests/linuxkpi/policyhost', 'tests/qemu-core/hosttest', 'tests/host-policy/hosttest', 'tests/host-policy/fixturehost']
	for path in paths {
		policyhost.command_checkpoint()!
		data := command(['git', '-C', root, 'show', commit + ':' + path], env, 64 * 1024 * 1024)!
		os.mkdir_all(os.dir(work + '/' + path))!
		if path in ['tests/linuxkpi/fixturehost', 'tests/linuxkpi/policyhost', 'tests/qemu-core/hosttest', 'tests/host-policy/hosttest', 'tests/host-policy/fixturehost'] { os.symlink(data, work + '/' + path)! }
		else { os.write_file(work + '/' + path, data)! }
	}
	source, header := output + '/gpu-present-host.c', output + '/gpu_present.h'
	for path in [source, header] { if os.is_link(path) || os.exists(path) { os.rm(path)! } }
	arch := $if amd64 { 'amd64' } $else { 'arm64' }
	command(['sh', work + '/build-support/compile-v-module', work + '/desktop/gpucore', source, '--arch', arch, '--header', header], env, 64 * 1024 * 1024)!
	command([compiler, '-std=c11', '-O2', '-D_GNU_SOURCE', '-Wno-unused-function', '-Wno-unused-label', '-Wno-unused-parameter', '-c', source, '-o', output + '/gpu-present-host.o'], os.environ(), 64 * 1024 * 1024)!
	flags := output + '/gpu_present_host_flags.v'
	if os.is_link(flags) || os.exists(flags) { os.rm(flags)! }
	os.write_file(flags, '// Generated by stage_host_gpu.py from committed desktop/gpucore.\nmodule main\n#flag @VMODROOT/gpu-present-host.o\n')!
	os.write_file(output + '/gpu-present-host.revision', commit + '\n')!
	println('Host software presenter staged from ' + commit[..8])
}

pub fn cli(argv []string) int {
	args := hosttest.parse_arguments(argv, [hosttest.Option{'--cc', true, []string{}}, hosttest.Option{'--v', true, []string{}}, hosttest.Option{'--revision', true, []string{}}], 1, 'stage_host_gpu <staged-desktop-directory> [--cc CC] [--v V] [--revision COMMIT]', 'stage_host_gpu') or { eprintln(err); return 2 }
	stage(args.positional[0], args.options['--cc'] or { hosttest.env_default('CC', 'clang') }, args.options['--v'] or { os.getenv('V') }, args.options['--revision'] or { 'HEAD' }) or { eprintln(err); return if policyhost.command_interrupted() { 130 } else { 1 } }
	return 0
}
