// Run with V from the repository root; the optional argument is libc++.1.tbd.
module main

import os
import crypto.sha256

fn main() {
	path := if os.args.len > 1 { os.args[1] } else {
		'/Library/Developer/CommandLineTools/SDKs/MacOSX.sdk/usr/lib/libc++.1.tbd'
	}
	source := os.read_file(path)!
	mut weak := []string{}
	for group in source.split('weak-symbols:')[1..] {
		start := group.index('[') or { panic('missing weak export list') }
		end := group.index(']') or { panic('unterminated weak export list') }
		for entry in group[start + 1..end].split(',') {
			name := entry.trim_space()
			if name !in weak { weak << name }
		}
	}
	assert weak.len > 0
	implemented := os.read_lines('compat/ios/runner/abi/cxx-symbols.txt')!
	mut supported := weak.filter(it in implemented)
	supported.sort()
	assert '__ZTISt12length_error' in supported && '__ZdlPv' in supported && '__Znwm' in supported
	mut result := '// SPDX-License-Identifier: GPL-2.0-or-later\n'
	result += '// Generated by build-support/ios/generate-cxx-weak.v from libc++.1.tbd.\n'
	result += '// SDK stub SHA256: ${sha256.sum(source.bytes()).hex()}\nmodule main\n\n'
	result += 'fn cxx_weak_symbol(symbol string) bool {\n\treturn symbol in [\n'
	for name in supported { result += "\t\t'${name}',\n" }
	result += '\t]!\n}\n'
	os.write_file('compat/ios/runner/cxx_weak.v', result)!
	println('Recorded ${supported.len} supported C++ weak exports from ${path}')
}
