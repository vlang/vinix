module minecraftnative

import json2
import os

fn download_entry(value json2.Any) !Download {
	return Download{safe_relative(text(field(value, 'path')!)!)!, text(field(value, 'url')!)!, text(field(value, 'sha1')!)!}
}

pub fn (source Source) select_libraries(version json2.Any) !([]Download, []Download) {
	mut mojang := []Download{}
	mut modules := map[string]bool{}
	for library in items(field(version, 'libraries')!)! {
		name := text(field(library, 'name')!)!
		parts := name.split(':')
		maven_path(name)!
		if parts[0] == 'org.lwjgl' {
			modules[parts[1] + ':' + parts[2]] = true
			if parts.len == 4 && parts[3].starts_with('natives-') { continue }
		}
		if !rule_allows(optional(library, 'rules', json2.Any(json2.Null{})), map[string]bool{})! {
			continue
		}
		artifact := optional(optional(library, 'downloads', json2.Any(map[string]json2.Any{})), 'artifact', json2.Any(json2.Null{}))
		if artifact is json2.Null { continue }
		mojang << download_entry(artifact)!
	}
	mut names := modules.keys()
	names.sort_with_compare(fn (a &string, b &string) int {
		left, right := a.all_before(':'), b.all_before(':')
		if left != right { return if left < right { -1 } else { 1 } }
		return if *a < *b {
			-1
		} else if *a > *b {
			1
		} else {
			0
		}
	})
	mut natives := []Download{}
	for pair in names {
		coordinate := 'org.lwjgl:' + pair + ':natives-linux-arm64'
		path := maven_path(coordinate)!
		url := source.maven + '/' + path
		payload := source.fetch(url + '.sha1') or {
			if source.fixture || err.msg().starts_with('failed to download ') {
				println('  no natives-linux-arm64 for ' + pair.replace(':', ' '))
				continue
			}
			return err
		}
		words := payload.bytestr().fields()
		if words.len == 0 { return error('Empty Maven SHA1 for ' + coordinate) }
		natives << Download{path, url, words[0]}
	}
	return mojang, natives
}

pub fn (source Source) download_assets(version json2.Any, root string, jobs int, index_only bool) !string {
	index := field(version, 'assetIndex')!
	id := safe_relative(text(field(index, 'id')!)!)!
	path := os.join_path(root, 'assets/indexes', id + '.json')
	source.download_to(text(field(index, 'url')!)!, path, text(field(index, 'sha1')!)!)!
	if index_only {
		println('  assets: index only (--no-assets)')
		return id
	}
	objects := field(json2.decode[json2.Any](os.read_file(path)!)!, 'objects')!
	mut entries := []Download{}
	mut positions := map[string]int{}
	for _, meta in objects.as_map() {
		hash := text(field(meta, 'hash')!)!
		if hash.len != 40 || !hash.bytes().all(it.is_digit() || (it >= `a` && it <= `f`)) {
			return error('Invalid asset SHA1')
		}
		file := 'assets/objects/' + hash[..2] + '/' + hash
		entry := Download{file, source.assets + '/' + hash[..2] + '/' + hash, hash}
		if file in positions {
			entries[positions[file]] = entry
		} else {
			positions[file] = entries.len
			entries << entry
		}
	}
	source.download_all(entries, root, 'assets', jobs)!
	return id
}

pub fn write_launch_env(destination string, version_id string, version json2.Any, classpath []string, asset_index string, game_root string) ! {
	arguments := optional(version, 'arguments', json2.Any(map[string]json2.Any{}))
	jvm := flatten_arguments(optional(arguments, 'jvm', json2.Any([]json2.Any{})), map[string]bool{})!
	mut filtered := []string{}
	mut skip := false
	for value in jvm {
		if skip {
			skip = false
			continue
		}
		if value == '-cp' {
			skip = true
			continue
		}
		filtered << value
	}
	game := optional(arguments, 'game', json2.Any([]json2.Any{}))
	demo := flatten_arguments(game, {
		'is_demo_user':          true
		'has_custom_resolution': true
	})!
	full := flatten_arguments(game, {
		'is_demo_user':          false
		'has_custom_resolution': true
	})!
	mut lines := ['# Generated by build-support/minecraft/fetch-minecraft — do not edit.']
	for pair in [
		['MC_VERSION', version_id],
		['MC_VERSION_TYPE', text(field(version, 'type')!)!],
		['MC_MAIN_CLASS', text(field(version, 'mainClass')!)!],
		['MC_ASSET_INDEX', asset_index],
		['MC_GAME_ROOT', game_root],
		['MC_JAVA_MAJOR',
			optional(optional(version, 'javaVersion', json2.Any(map[string]json2.Any{})), 'majorVersion', json2.Any(21)).str()],
		['MC_CLASSPATH', classpath.map(game_root + '/' + it).join(':')],
		['MC_JVM_ARGS', filtered.join(' ')],
		['MC_GAME_ARGS_DEMO', demo.join(' ')],
		['MC_GAME_ARGS_FULL', full.join(' ')],
	] {
		lines << pair[0] + '=' + shell_quote(pair[1])
	}
	os.write_file(destination, lines.join('\n') + '\n')!
}
