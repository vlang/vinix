module asahiuapi

import crypto.sha256
import strconv

pub struct Field {
pub:
	name      string
	type_name string
	count     int
}

pub struct Record {
pub:
	name   string
	fields []Field
}

pub fn v_name(name string) string {
	return name.trim_string_left('drm_asahi_').split('_').map(it.capitalize()).join('')
}

fn strip_comments(text string) !string {
	mut out := []u8{cap: text.len}
	mut i := 0
	for i < text.len {
		if i + 1 < text.len && text[i] == `/` && text[i + 1] == `*` {
			i += 2
			for i + 1 < text.len && !(text[i] == `*` && text[i + 1] == `/`) {
				if text[i] == `\n` { out << `\n` }
				i++
			}
			if i + 1 >= text.len { return error('unterminated C comment') }
			i += 2
			out << ` `
		} else {
			out << text[i]
			i++
		}
	}
	return out.bytestr()
}

pub fn records(header string) ![]Record {
	mut result := []Record{}
	mut fields := []Field{}
	mut current := ''
	mut macros := map[string]int{}
	for raw in strip_comments(header)!.split_into_lines() {
		line := raw.trim_space()
		words := line.fields()
		if words.len == 3 && words[0] == '#define' && words[2].bytes().all(it.is_digit()) {
			macros[words[1]] = strconv.atoi(words[2])!
		}
		if current == '' {
			if line.starts_with('struct drm_asahi_') && line.ends_with(' {') {
				if words.len != 3 { return error('unsupported record declaration: ${line}') }
				current = words[1]
				fields = []Field{}
			}
			continue
		}
		if line == '};' {
			if fields.len == 0 || result.any(it.name == current) {
				return error('empty/duplicate record: ${current}')
			}
			result << Record{ name: current, fields: fields }
			current = ''
			continue
		}
		if line == '' { continue }
		if !line.ends_with(';') || (words.len != 2 && words.len != 3) {
			return error('unsupported ${current} member: ${line}')
		}
		type_name := if words.len == 3 && words[0] == 'struct' { words[1] } else { words[0] }
		if type_name !in ['__u8', '__u16', '__u32', '__u64', '__s32', '__s64'] && !type_name.starts_with('drm_asahi_') {
			return error('unsupported member type: ${type_name}')
		}
		mut name := words.last().trim_right(';')
		mut count := 0
		if name.contains('[') {
			bound := name.all_after('[').trim_right(']')
			count = if bound in macros { macros[bound] } else { strconv.atoi(bound)! }
			if count <= 0 || count > 4096 { return error('invalid array bound') }
			name = name.all_before('[')
		}
		if name == '' || !name.bytes().all(it.is_alnum() || it == `_`) || fields.any(it.name == name) {
			return error('invalid/duplicate field: ${name}')
		}
		fields << Field{ name: name, type_name: type_name, count: count }
	}
	if current != '' || result.len == 0 { return error('incomplete UAPI header') }
	return result
}

fn field_type(field Field, foreign bool) string {
	base := if field.type_name.starts_with('drm_asahi_') {
		if foreign { 'C.' + field.type_name } else { v_name(field.type_name) }
	} else {
		field.type_name.trim_string_left('__').replace('s', 'i')
	}
	return if field.count == 0 { base } else { '[${field.count}]${base}' }
}

pub fn generate(header string) !string {
	mut lines := ['// SPDX-License-Identifier: MIT',
		'// Generated by tools/agx-re/generate_asahi_uapi.v. Do not edit.',
		'// Asahi UAPI header SHA-256: ${sha256.sum(header.bytes()).hex()}', 'module asahi', '']
	for record in records(header)! {
		lines << 'pub struct ${v_name(record.name)} {\npub mut:'
		for field in record.fields {
			lines << '\t${field.name.to_lower()} ${field_type(field, false)}'
		}
		lines << '}\n'
	}
	return lines.join('\n')
}

// Compile this V oracle against the actual C header, independently checking
// every size and member offset, including nested structs and fixed arrays.
pub fn oracle(header string) !string {
	mut lines := ['module main', 'import drm.asahi', '#include "asahi_drm.h"', '']
	for record in records(header)! {
		lines << 'struct C.${record.name} {'
		for field in record.fields { lines << '\t${field.name} ${field_type(field, true)}' }
		lines << '}\n'
	}
	lines << 'fn main() {'
	lines << '\tmut wire := []u64{}'
	for name in ['get_params', 'get_time', 'vm_create', 'vm_destroy', 'vm_bind', 'gem_create',
		'gem_mmap_offset', 'gem_bind_object', 'queue_create', 'queue_destroy', 'submit', 'gem_madvise'] {
		lines << '\tassert asahi.${name} == u32(C.DRM_COMMAND_BASE) + u32(C.DRM_ASAHI_${name.to_upper()})'
		lines << '\twire << linux_ioctl_word(u32(C.DRM_IOCTL_ASAHI_${name.to_upper()}))'
	}
	for name in ['cmd_render', 'cmd_compute', 'set_vertex_attachments', 'set_fragment_attachments',
		'set_compute_attachments', 'barrier_none', 'bind_unbind', 'bind_read', 'bind_write',
		'bind_single_page', 'gem_writeback', 'gem_vm_private', 'render_vertex_scratch',
		'render_process_empty_tiles', 'render_no_vertex_clustering', 'render_dbias_is_int'] {
		lines << '\tassert u32(asahi.${name}) == u32(C.DRM_ASAHI_${name.to_upper()})'
	}
	for record in records(header)! {
		name := 'asahi.' + v_name(record.name)
		lines << '\tassert sizeof(${name}) == sizeof(C.${record.name}), "${record.name} size"'
		for field in record.fields {
			lines << '\tassert __offsetof(${name}, ${field.name.to_lower()}) == __offsetof(C.${record.name}, ${field.name}), "${record.name}.${field.name} offset"'
		}
	}
	lines << '\tprintln("Asahi ioctl encodings: " + wire.str())'
	lines << '\tprintln("Asahi UAPI: ${records(header)!.len} records and every field match the packaged C header")\n}\n'
	// The pinned drm.h selects the host's ioctl macros. The BSD/macOS
	// encoding swaps the direction bits for read and write compared to Linux.
	lines << 'fn linux_ioctl_word(raw u32) u64 {
		$if linux {
			return u64(raw)
		} $else {
			mut direction := u32(0)
			if raw & u32(C.IOC_IN) != 0 { direction |= 1 }
			if raw & u32(C.IOC_OUT) != 0 { direction |= 2 }
			return u64((direction << 30) | (raw & 0x1fff_ffff))
		}
	}'
	return lines.join('\n')
}
