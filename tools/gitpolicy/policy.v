module gitpolicy

import os
import rand

pub const max_blob_size = i64(5 * 1024 * 1024)
pub const max_report_size = i64(64 * 1024)

pub struct FileVersion {
pub:
	object string
	path   string
	size   i64
}

pub struct Violation {
pub:
	file   FileVersion
	reason string
}

pub fn is_result(path string) bool {
	return path.starts_with('tests/') && path.contains('/results/')
}

// Retain source snapshots and short human-readable reports. Compiled C is
// output even though its extension looks like source; hand-written C survives.
pub fn reason(path string, size i64, prefix string) string {
	if size > max_blob_size {
		return 'file exceeds 5 MiB; store it as an external artifact'
	}
	if !is_result(path) {
		return ''
	}
	ext := os.file_ext(path).to_lower()
	if ext == '.md' {
		return if size <= max_report_size { '' } else { 'result report exceeds 64 KiB' }
	}
	if ext == '.c' {
		if os.file_name(path) == 'blob.c' || prefix.contains('// V comptime_definitions:')
			|| prefix.contains('// Generated by V') {
			return 'generated compiler output belongs in external artifact storage'
		}
		return ''
	}
	if ext in ['.v', '.h', '.s', '.sh', '.diff', '.patch'] {
		return ''
	}
	return 'generated test result belongs in external artifact storage'
}

pub fn git(args []string) !string {
	mut command := ['git']
	command << args
	result := os.exec(command)
	if result.exit_code != 0 {
		return error('git ' + args.join(' ') + ': ' + result.output.trim_space())
	}
	return result.output
}

// File-backed stdin avoids pipe deadlocks when a batch produces more output
// than fits in a pipe before it has finished consuming its input.
pub fn git_input(args []string, input string) !string {
	tmp := os.join_path(os.temp_dir(), 'vinix-git-policy-' + rand.uuid_v4())
	os.mkdir(tmp)!
	defer { os.rmdir_all(tmp) or {} }
	path := os.join_path(tmp, 'stdin')
	os.write_file(path, input)!
	mut process := os.new_process(os.find_abs_path_of_executable('git')!)
	process.set_args(args)
	process.set_redirect_stdio_merged()
	process.set_stdin_path(path)
	process.run()
	output := process.stdout_slurp()
	process.wait()
	code := process.code
	process.close()
	if code != 0 { return error('git ' + args.join(' ') + ': ' + output.trim_space()) }
	return output
}

pub fn versions(base string, tip string) ![]FileVersion {
	return versions_excluding(if base == '' { []string{} } else { [base] }, tip)
}

pub fn versions_excluding(bases []string, tip string) ![]FileVersion {
	mut revisions := [tip]
	for base in bases { revisions << '^' + base }
	// Scan every changed path, including merge resolutions and files later
	// deleted. rev-list --objects alone can hide a second path for the same blob.
	mut args := ['log', '--format=', '--raw', '-z', '--no-renames', '--no-abbrev', '-m']
	args << revisions
	args << '--'
	changes := git(args)!
	fields := changes.split('\x00')
	mut paths := map[string][]string{}
	mut seen := map[string]bool{}
	mut i := 0
	for i < fields.len {
		header := fields[i].trim_left('\n')
		i++
		if !header.starts_with(':') { continue }
		if i >= fields.len { return error('truncated Git diff record') }
		path := fields[i]
		i++
		meta := header.fields()
		if meta.len != 5 { return error('invalid Git diff record: ' + header) }
		if meta[4] == 'D' || meta[1] == '160000' { continue }
		object := meta[3]
		key := object + ':' + path
		if seen[key] { continue }
		seen[key] = true
		paths[object] << path
	}
	if paths.len == 0 { return []FileVersion{} }
	sizes := git_input(['cat-file', '--batch-check=%(objectname) %(objecttype) %(objectsize)'],
		paths.keys().join('\n') + '\n')!
	mut files := []FileVersion{}
	for line in sizes.split_into_lines() {
		meta := line.fields()
		if meta.len != 3 || meta[1] != 'blob' { return error('invalid blob metadata: ' + line) }
		for path in paths[meta[0]] {
			files << FileVersion{ object: meta[0], path: path, size: meta[2].i64() }
		}
	}
	return files
}

pub fn inspect(file FileVersion) !string {
	mut prefix := ''
	if is_result(file.path) && file.path.ends_with('.c') && file.size <= max_blob_size {
		content := git(['cat-file', 'blob', file.object])!
		prefix = content[..if content.len < 2048 { content.len } else { 2048 }]
	}
	return reason(file.path, file.size, prefix)
}

pub fn audit(base string, tip string) ![]Violation {
	return audit_excluding(if base == '' { []string{} } else { [base] }, tip)
}

pub fn audit_excluding(bases []string, tip string) ![]Violation {
	mut violations := []Violation{}
	for file in versions_excluding(bases, tip)! {
		why := inspect(file)!
		if why != '' { violations << Violation{ file: file, reason: why } }
	}
	return violations
}
